def resolve_dynaworld_path(path: str | Path) -> Path:
    value = Path(path)
    if value.is_absolute():
        return value
    return DYNAWORLD_ROOT / value


def parse_csv_strings(value: str) -> list[str]:
    return [part.strip() for part in value.split(",") if part.strip()]


def parse_csv_ints(value: str) -> list[int]:
    return [int(part) for part in parse_csv_strings(value)]


def parse_csv_floats(value: str) -> list[float]:
    return [float(part) for part in parse_csv_strings(value)]


def parse_csv_bools(value: str) -> list[bool]:
    parsed = []
    for part in parse_csv_strings(value):
        token = part.lower()
        if token in {"1", "true", "yes", "on"}:
            parsed.append(True)
        elif token in {"0", "false", "no", "off"}:
            parsed.append(False)
        else:
            raise ValueError(f"Expected boolean token, got {part!r}.")
    return parsed


