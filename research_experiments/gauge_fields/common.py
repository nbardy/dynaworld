def write_generated_jsonc(path: Path, payload: Mapping[str, Any], *, generated_by: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = f"// Generated by {generated_by}\n"
    path.write_text(header + json.dumps(payload, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    return path


