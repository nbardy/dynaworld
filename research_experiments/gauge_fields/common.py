def parse_gauge_matrix_args(
    *,
    description: str,
    default_output_root: str,
) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=description)
    parser.add_argument("--output-root", default=default_output_root)
    parser.add_argument("--steps", type=int, default=80)
    parser.add_argument("--device", default="mps")
    parser.add_argument("--no-wandb", action="store_true")
    parser.add_argument("--only", default=None, help="Comma-separated run names to execute.")
    return parser.parse_args()


def run_gauge_matrix(runs: Sequence[Mapping[str, Any]], args: argparse.Namespace) -> None:
    output_root = resolve_dynaworld_path(args.output_root)
    selected = set(parse_csv_strings(args.only)) if args.only else None

    for spec in runs:
        if selected is not None and spec["name"] not in selected:
            continue

        output_dir = output_root / str(spec["name"])
        cmd = [
            "uv",
            "run",
            "python",
            str(spec["script"]),
            str(spec["config"]),
            "--device",
            str(args.device),
            "--steps",
            str(args.steps),
            "--output-dir",
            str(output_dir),
            *list(spec.get("extra_args", [])),
        ]
        if args.no_wandb:
            cmd.append("--no-wandb")

        print(f"\n==> Running {spec['name']}", flush=True)
        print(" ".join(cmd), flush=True)
        start = time.perf_counter()
        status = "completed"
        returncode = 0
        try:
            subprocess.run(cmd, cwd=resolve_dynaworld_path("."), check=True)
        except subprocess.CalledProcessError as exc:
            status = "failed"
            returncode = int(exc.returncode)
        elapsed = time.perf_counter() - start
        write_json(
            output_dir / "wall_clock.json",
            {
                "name": spec["name"],
                "status": status,
                "returncode": returncode,
                "elapsed_sec": elapsed,
                "elapsed_min": elapsed / 60.0,
                "steps": args.steps,
                "device": args.device,
                "command": cmd,
            },
        )
        print(f"<== {spec['name']} {status} in {elapsed:.2f}s", flush=True)
        if returncode != 0:
            sys.exit(returncode)


